/*
# StudentPulse schema — students and analytics results

1. New Tables
- `students`: one row per student record with academic metrics.
  - student_id (text, unique) — institutional identifier
  - attendance (numeric 0–100) — attendance percentage
  - study_hours (numeric >= 0) — self-reported weekly study hours
  - previous_score (numeric 0–100) — prior examination score
  - assignment_marks (numeric 0–100) — average assignment score
  - exam_marks (numeric 0–100) — current examination score
  - created_at (timestamptz)
- `analytics_results`: persisted aggregated metrics computed by the MapReduce pipeline.
  - metric_name (text) — e.g. "avg_exam_marks"
  - metric_value (numeric) — computed value
  - dataset_version (text) — source dataset label
  - calculated_at (timestamptz)

2. Security
- This is a single-tenant demo app with no sign-in screen, so policies target
  `anon, authenticated` and the data is intentionally shared/public.
- RLS enabled on both tables.
- Full CRUD granted to anon + authenticated on both tables.
- USING (true) / WITH CHECK (true) is acceptable here because all data is
  intentionally public/shared (single-tenant, no auth).

3. Important notes
- Score columns are constrained to 0–100; study_hours is non-negative.
- Identity columns are used for ids (no sequence grant needed).
*/

CREATE TABLE IF NOT EXISTS public.students (
  id bigint generated by default as identity primary key,
  student_id text not null unique,
  attendance numeric(5,2),
  study_hours numeric(5,2),
  previous_score numeric(5,2),
  assignment_marks numeric(5,2),
  exam_marks numeric(5,2),
  created_at timestamptz not null default now(),
  constraint attendance_range check (attendance is null or attendance between 0 and 100),
  constraint study_hours_nonnegative check (study_hours is null or study_hours >= 0),
  constraint previous_score_range check (previous_score is null or previous_score between 0 and 100),
  constraint assignment_marks_range check (assignment_marks is null or assignment_marks between 0 and 100),
  constraint exam_marks_range check (exam_marks is null or exam_marks between 0 and 100)
);

ALTER TABLE public.students ENABLE ROW LEVEL SECURITY;

GRANT SELECT, INSERT, UPDATE, DELETE ON public.students TO anon, authenticated;

DROP POLICY IF EXISTS "anon_select_students" ON public.students;
CREATE POLICY "anon_select_students" ON public.students FOR SELECT
  TO anon, authenticated USING (true);

DROP POLICY IF EXISTS "anon_insert_students" ON public.students;
CREATE POLICY "anon_insert_students" ON public.students FOR INSERT
  TO anon, authenticated WITH CHECK (true);

DROP POLICY IF EXISTS "anon_update_students" ON public.students;
CREATE POLICY "anon_update_students" ON public.students FOR UPDATE
  TO anon, authenticated USING (true) WITH CHECK (true);

DROP POLICY IF EXISTS "anon_delete_students" ON public.students;
CREATE POLICY "anon_delete_students" ON public.students FOR DELETE
  TO anon, authenticated USING (true);

CREATE TABLE IF NOT EXISTS public.analytics_results (
  id bigint generated by default as identity primary key,
  metric_name text not null,
  metric_value numeric,
  dataset_version text,
  calculated_at timestamptz not null default now()
);

ALTER TABLE public.analytics_results ENABLE ROW LEVEL SECURITY;

GRANT SELECT, INSERT, UPDATE, DELETE ON public.analytics_results TO anon, authenticated;

DROP POLICY IF EXISTS "anon_select_analytics" ON public.analytics_results;
CREATE POLICY "anon_select_analytics" ON public.analytics_results FOR SELECT
  TO anon, authenticated USING (true);

DROP POLICY IF EXISTS "anon_insert_analytics" ON public.analytics_results;
CREATE POLICY "anon_insert_analytics" ON public.analytics_results FOR INSERT
  TO anon, authenticated WITH CHECK (true);

DROP POLICY IF EXISTS "anon_update_analytics" ON public.analytics_results;
CREATE POLICY "anon_update_analytics" ON public.analytics_results FOR UPDATE
  TO anon, authenticated USING (true) WITH CHECK (true);

DROP POLICY IF EXISTS "anon_delete_analytics" ON public.analytics_results;
CREATE POLICY "anon_delete_analytics" ON public.analytics_results FOR DELETE
  TO anon, authenticated USING (true);

CREATE INDEX IF NOT EXISTS students_student_id_idx ON public.students(student_id);
CREATE INDEX IF NOT EXISTS analytics_metric_name_idx ON public.analytics_results(metric_name);
